#!/usr/bin/env bash
# Generate THIRD_PARTY_NOTICES (full license texts) and third_party_licenses/ for archives.
# Dependency set is the union across all release GOOS/GOARCH targets (go-licenses v1.6.0).
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

GO_LICENSES_VERSION="v1.6.0"
SCAN="./cmd/linkwarden"

PLATFORMS=(
  "linux:amd64"
  "linux:arm64"
  "darwin:amd64"
  "darwin:arm64"
  "windows:amd64"
  "windows:arm64"
)

if ! command -v go-licenses >/dev/null 2>&1; then
  go install "github.com/google/go-licenses@${GO_LICENSES_VERSION}"
fi
export PATH="$(go env GOPATH)/bin:$PATH"

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

declare -A module_version=()
declare -A module_license=()

for plat in "${PLATFORMS[@]}"; do
  IFS=: read -r goos goarch <<<"$plat"
  export GOOS="$goos" GOARCH="$goarch"

  while IFS=, read -r pkg _ lic; do
    pkg="${pkg//\"/}"
    lic="${lic//\"/}"
    [[ -n "$pkg" ]] || continue
    module_license["$pkg"]="$lic"
  done < <(go-licenses csv "$SCAN")

  while read -r modver; do
    [[ -n "$modver" ]] || continue
    path="${modver%@*}"
    ver="${modver#*@}"
    module_version["$path"]="$ver"
  done < <(
    go list -deps -f '{{if and .Module (not .Standard)}}{{.Module.Path}}@{{.Module.Version}}{{end}}' "$SCAN" | sort -u
  )

  save_dir="$work/save/${goos}_${goarch}"
  go-licenses save --save_path="$save_dir" --force "$SCAN" >/dev/null

  while IFS= read -r abs; do
    rel="${abs#"$save_dir"/}"
    [[ -n "$rel" ]] || continue
    dest="$work/union/$rel"
    if [[ ! -e "$dest" ]]; then
      mkdir -p "$(dirname "$dest")"
      cp -a "$abs" "$dest"
    fi
  done < <(find "$save_dir" -type f)
done

rm -rf third_party_licenses
mkdir -p third_party_licenses
cp -a "$work/union/." third_party_licenses/
if [[ -f LICENSE ]]; then
  mkdir -p third_party_licenses/github.com/swtormy-agents/linkwarden-cli
  cp LICENSE third_party_licenses/github.com/swtormy-agents/linkwarden-cli/LICENSE
fi

mapfile -t modules < <(printf '%s\n' "${!module_version[@]}" | sort)

{
  echo "Third-party notices for linkwarden-cli"
  echo "Generated by scripts/generate-third-party-notices.sh (go-licenses ${GO_LICENSES_VERSION})"
  echo "Full license file tree: third_party_licenses/"
  echo "Includes dependencies bundled in release builds for:"
  for plat in "${PLATFORMS[@]}"; do
    IFS=: read -r goos goarch <<<"$plat"
    echo "  ${goos}/${goarch}"
  done
  echo ""
} > THIRD_PARTY_NOTICES

find_license_file() {
  local dir="$1"
  local f
  for f in LICENSE LICENSE.txt LICENSE.md; do
    if [[ -f "$dir/$f" ]]; then
      echo "$dir/$f"
      return 0
    fi
  done
  return 1
}

for mod in "${modules[@]}"; do
  ver="${module_version[$mod]:-}"
  if [[ -z "$ver" ]]; then
    ver="(devel)"
  fi
  lic="${module_license[$mod]:-unknown}"
  dir="$work/union/$mod"
  if [[ "$mod" == "github.com/swtormy-agents/linkwarden-cli" ]]; then
    dir="$ROOT"
  fi

  if ! lic_file="$(find_license_file "$dir")"; then
    echo "missing license file for $mod ($ver)" >&2
    exit 1
  fi

  {
    echo "================================================================================"
    echo "Module: ${mod} ${ver}"
    echo "License: ${lic}"
    echo "================================================================================"
    echo ""
    cat "$lic_file"
    echo ""
    echo ""
  } >> THIRD_PARTY_NOTICES
done

echo "Wrote THIRD_PARTY_NOTICES ($(wc -l < THIRD_PARTY_NOTICES) lines) and third_party_licenses/"
